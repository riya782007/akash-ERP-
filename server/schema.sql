-- Mehers ERP schema for Supabase Postgres.
-- The app applies this automatically on first start (idempotent), or you can paste it
-- into Supabase → SQL Editor and run it once.
-- Money columns are stored in paise (BIGINT). Row Level Security is enabled with no
-- policies, so Supabase's public Data API (anon/authenticated keys) cannot read any
-- table; only the server's direct Postgres connection can.

CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY, name TEXT NOT NULL, username TEXT NOT NULL UNIQUE, password TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('owner','cashier','technician','accountant')), active INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS products(id TEXT PRIMARY KEY, name TEXT NOT NULL, brand TEXT NOT NULL, category TEXT NOT NULL, sku TEXT NOT NULL UNIQUE, price BIGINT NOT NULL CHECK(price>=0), cost BIGINT NOT NULL CHECK(cost>=0), tax INTEGER NOT NULL DEFAULT 1800, reorder INTEGER NOT NULL DEFAULT 3);
CREATE TABLE IF NOT EXISTS units(id TEXT PRIMARY KEY, product_id TEXT NOT NULL REFERENCES products(id), imei TEXT UNIQUE, condition TEXT NOT NULL, location TEXT NOT NULL, status TEXT NOT NULL CHECK(status IN ('available','sold','returned_to_supplier','inspection')), cost BIGINT NOT NULL CHECK(cost>=0));
CREATE TABLE IF NOT EXISTS documents(id TEXT PRIMARY KEY, kind TEXT NOT NULL, date TEXT NOT NULL, party TEXT NOT NULL, amount BIGINT NOT NULL, status TEXT NOT NULL, data TEXT NOT NULL, actor TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), seq BIGINT GENERATED ALWAYS AS IDENTITY);
CREATE TABLE IF NOT EXISTS sale_lines(sale_id TEXT NOT NULL REFERENCES documents(id), unit_id TEXT NOT NULL REFERENCES units(id), price BIGINT NOT NULL, discount BIGINT NOT NULL, tax INTEGER NOT NULL, PRIMARY KEY(sale_id,unit_id));
CREATE TABLE IF NOT EXISTS movements(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, unit_id TEXT NOT NULL REFERENCES units(id), document_id TEXT REFERENCES documents(id), from_location TEXT, to_location TEXT, action TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS ledger(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, document_id TEXT NOT NULL REFERENCES documents(id), account TEXT NOT NULL, debit BIGINT NOT NULL DEFAULT 0 CHECK(debit>=0), credit BIGINT NOT NULL DEFAULT 0 CHECK(credit>=0));
CREATE TABLE IF NOT EXISTS employees(id TEXT PRIMARY KEY, name TEXT NOT NULL, role TEXT NOT NULL, salary BIGINT NOT NULL, incentive BIGINT NOT NULL DEFAULT 100);
CREATE TABLE IF NOT EXISTS attendance(employee_id TEXT NOT NULL REFERENCES employees(id), date TEXT NOT NULL, check_in TEXT NOT NULL, check_out TEXT, PRIMARY KEY(employee_id,date));
CREATE TABLE IF NOT EXISTS audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor TEXT NOT NULL, action TEXT NOT NULL, document_id TEXT, details TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS requests(key TEXT PRIMARY KEY, user_id TEXT NOT NULL, result TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS closings(date TEXT PRIMARY KEY, expected BIGINT NOT NULL, counted BIGINT NOT NULL, difference BIGINT NOT NULL, notes TEXT NOT NULL, actor TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS ai_requests(key TEXT PRIMARY KEY, date TEXT NOT NULL, user_id TEXT NOT NULL, task TEXT NOT NULL DEFAULT '', result TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS login_attempts(ip TEXT PRIMARY KEY, count INTEGER NOT NULL, until BIGINT NOT NULL);

CREATE INDEX IF NOT EXISTS documents_kind_idx ON documents(kind);
CREATE INDEX IF NOT EXISTS documents_date_idx ON documents(date);
CREATE INDEX IF NOT EXISTS units_product_idx ON units(product_id);
CREATE INDEX IF NOT EXISTS ledger_account_idx ON ledger(account);
CREATE INDEX IF NOT EXISTS ledger_document_idx ON ledger(document_id);
CREATE INDEX IF NOT EXISTS movements_unit_idx ON movements(unit_id);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON sessions(user_id);
CREATE INDEX IF NOT EXISTS ai_requests_date_idx ON ai_requests(date);
CREATE INDEX IF NOT EXISTS movements_document_idx ON movements(document_id);
CREATE INDEX IF NOT EXISTS sale_lines_unit_idx ON sale_lines(unit_id);

